/*
 * ============================================================================
 * 顺序表操作集 — C 语言实现
 * ============================================================================
 * 
 * 数据结构回顾（由裁判程序预定义）：
 *   typedef int Position;              // Position 本质是 int，表示数组下标
 *   typedef struct LNode *List;        // List 是指向 LNode 的指针
 *   struct LNode {
 *       ElementType Data[MAXSIZE];     // 固定大小的数组，MAXSIZE=5
 *       Position Last;                 // 记录「最后一个有效元素」的下标
 *   };
 * 
 * 约定：
 *   - 空表：Last = -1，Data 数组中没有有效数据
 *   - 有效元素范围：Data[0] ~ Data[Last]，共 Last+1 个元素
 *   - ERROR = -1，用作 Find 未找到时的返回值
 */

/* ---------------------------------------------------------------------------
 * MakeEmpty — 创建并返回一个空线性表
 * ---------------------------------------------------------------------------
 * 思路：在堆上分配一个 LNode 结构体，将 Last 置为 -1 表示空表。
 * 注意：C 语言用 malloc 申请内存；C++ 版本用 new。
 */
List MakeEmpty()
{
    // 在堆上分配一块 sizeof(struct LNode) 大小的内存，强转为 List 类型
    List L = (List)malloc(sizeof(struct LNode));
    // 初始化为空表：Last = -1 表示没有任何有效数据
    L->Last = -1;
    // 返回指向新创建表结构的指针
    return L;
}

/* ---------------------------------------------------------------------------
 * Find — 在线性表中查找元素 X，返回其位置（下标）
 * ---------------------------------------------------------------------------
 * 思路：从 0 到 Last 线性扫描 Data 数组，找到则返回下标，找不到返回 ERROR。
 * 时间复杂度 O(n)，空间复杂度 O(1)。
 */
Position Find(List L, ElementType X)
{
    // 遍历所有有效元素：i 从 0 到 L->Last（包含）
    for (Position i = 0; i <= L->Last; i++) {
        // 若当前元素与目标 X 相等
        if (L->Data[i] == X)
            return i;   // 找到，返回其下标
    }
    // 扫描完毕仍未找到，返回 ERROR（即 -1）
    return ERROR;
}

/* ---------------------------------------------------------------------------
 * Insert — 将元素 X 插入到位置 P
 * ---------------------------------------------------------------------------
 * 插入流程：
 *   1. 先检查表是否已满（Last+1 >= MAXSIZE） — 必须在其他检查之前！
 *      因为如果表已满，即使 P 合法也无法插入，样例输出中满表时打印 "FULL"。
 *   2. 再检查 P 是否合法：P 必须在 [0, Last+1] 范围内。
 *      - P=0 表示插在表头
 *      - P=Last+1 表示插在表尾之后
 *   3. 将 Data[P] ~ Data[Last] 的元素整体向后移动一格，腾出空位。
 *      移动顺序必须从后往前（从 Last 到 P），否则会覆盖未移动的数据。
 *   4. 将 X 放入 Data[P]，Last 加 1。
 *
 * 关键细节：
 *   - L->Last + 1 就是当前表中的元素个数
 *   - 合法插入范围是 [0, Last+1]（共 Last+2 个可选位置）
 */
bool Insert(List L, ElementType X, Position P)
{
    /* 第 1 步：检查表是否已满 */
    // Last+1 = 当前元素个数；若 >= MAXSIZE 则无法再插入
    if (L->Last + 1 >= MAXSIZE) {
        printf("FULL");         // 不换行，后续裁判代码会补齐整行
        return false;           // 插入失败
    }

    /* 第 2 步：检查插入位置 P 是否合法 */
    // P < 0 或 P > Last+1（即越过了表尾之后的第一位）均非法
    if (P < 0 || P > L->Last + 1) {
        printf("ILLEGAL POSITION");
        return false;
    }

    /* 第 3 步：从最后一个元素开始，逐个向后移动，直到腾出 P 位置 */
    // i 从 Last 递减到 P，Data[i] → Data[i+1]
    for (Position i = L->Last; i >= P; i--) {
        L->Data[i + 1] = L->Data[i];
    }

    /* 第 4 步：放入新元素，更新 Last 标记 */
    L->Data[P] = X;             // 将 X 填入空出的位置 P
    L->Last++;                  // 有效元素个数 +1
    return true;                // 插入成功
}

/* ---------------------------------------------------------------------------
 * Delete — 删除位置 P 的元素
 * ---------------------------------------------------------------------------
 * 删除流程：
 *   1. 检查 P 是否合法：P 必须在 [0, Last] 范围内。
 *      注意和 Insert 的区别：删除不存在 "Last+1" 这个越界位置，
 *      因为 Last+1 处本来就没有元素可删。
 *   2. 将 Data[P+1] ~ Data[Last] 的元素整体向前移动一格，覆盖 P 位置。
 *      移动顺序必须从前往后（从 P 到 Last-1），否则会覆盖未移动的数据。
 *   3. Last 减 1。
 *
 * 非法时输出格式："POSITION {P} EMPTY"，P 是传入的参数值。
 */
bool Delete(List L, Position P)
{
    /* 第 1 步：检查删除位置 P 是否合法 */
    // 合法范围是 [0, Last]，超出则打印错误信息
    if (P < 0 || P > L->Last) {
        // 注意 P 要用 %d 打印其具体值
        printf("POSITION %d EMPTY", P);
        return false;           // 删除失败
    }

    /* 第 2 步：从 P 的下一位开始，逐个前移，覆盖掉 P 位置的元素 */
    // i 从 P 递增到 Last-1（即 Last 的前一位），Data[i+1] → Data[i]
    for (Position i = P; i < L->Last; i++) {
        L->Data[i] = L->Data[i + 1];
    }

    /* 第 3 步：更新 Last 标记 */
    L->Last--;                  // 有效元素个数 -1
    return true;                // 删除成功
}
