/*
 * Length — 返回链式表的表长（结点个数）
 *
 * 算法：从头结点开始遍历链表，每访问一个结点计数器 +1，
 * 直到遇到 NULL 为止。
 *
 * 时间复杂度 O(n)，空间复杂度 O(1)
 */
int Length(List L)
{
    int len = 0;              // 计数器，初始为 0
    while (L != NULL) {       // 遍历链表，L 为当前结点
        len++;                // 当前结点计入长度
        L = L->Next;          // 移动到下一个结点
    }
    return len;               // 返回结点总数
}
